function replaceDisplayText(value) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const key = value.slice(leading.length, value.length - trailing.length || undefined);
  const translation = replacements[key];
  if (translation === undefined) return value;
  applied.set(key, (applied.get(key) ?? 0) + 1);
  return `${leading}${translation}${trailing}`;
}

function translateMarkdown(value) {
  let inFence = false;
  return value.split(/(\r?\n)/).map((line) => {
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      return line;
    }
    if (inFence) return line;
    return line.split(/(`+[^`]*`+)/g).map((part, index) => index % 2 ? part : replaceDisplayText(part)).join("");
  }).join("");
}

function translateDisplayCalls(source, name) {
  let result = "";
  let cursor = 0;
  while (cursor < source.length) {
    const start = source.indexOf(`${name}(`, cursor);
    if (start < 0) break;
    let end = start + name.length + 1;
    let depth = 1;
    let quote = "";
    while (end < source.length && depth > 0) {
      const char = source[end];
      if (quote) {
        if (char === "\\") end++;
        else if (char === quote) quote = "";
      } else if (char === "`" || char === "'" || char === '"') quote = char;
      else if (char === "(") depth++;
      else if (char === ")") depth--;
      end++;
    }
    if (depth !== 0) break;
    result += source.slice(cursor, start);
    const call = source.slice(start, end);
    const translated = call.replace(/`([^`]*)`|"([^"\\]*(?:\\.[^"\\]*)*)"|'([^'\\]*(?:\\.[^'\\]*)*)'/g, (match, template, doubleQuoted, singleQuoted) => {
      const value = template ?? doubleQuoted ?? singleQuoted;
      const replacement = replaceDisplayText(value);
      if (replacement === value) return match;
      const quote = match[0];
      return `${quote}${replacement}${quote}`;
    });
    result += translated;
    cursor = end;
  }
  return result + source.slice(cursor);
}

